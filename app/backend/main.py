MAX_FILE_SIZE = 10 * 1024 * 1024


def extract_pdf_text(pdf_path: Path) -> str:
    """Extract text from a text-based PDF."""

    try:
        reader = PdfReader(str(pdf_path))

        if reader.is_encrypted:
            raise HTTPException(
                status_code=400,
                detail="The PDF is password-protected. Please upload an unlocked PDF.",
            )

        pages = []

        for page in reader.pages:
            page_text = page.extract_text()

            if page_text:
                pages.append(page_text)

        extracted_text = "\n".join(pages).strip()

        if not extracted_text:
            raise HTTPException(
                status_code=400,
                detail=(
                    "No readable text was found in the PDF. "
                    "Please upload a text-based PDF instead of a scanned image."
                ),
            )

        return extracted_text

    except HTTPException:
        raise

    except Exception as exc:
        logger.exception("PDF extraction failed")

        raise HTTPException(
            status_code=400,
            detail="Could not read this PDF. Please upload a valid PDF resume.",
        ) from exc


def read_analysis_json() -> dict:
    """Read and validate the final ML analysis JSON."""

    if not FINAL_JSON.exists():
        raise HTTPException(
            status_code=500,
            detail="The ML pipeline did not generate the expected JSON result.",
        )

    try:
        with FINAL_JSON.open("r", encoding="utf-8") as file:
            result = json.load(file)

    except json.JSONDecodeError as exc:
        logger.exception("Invalid JSON generated by ML pipeline")

        raise HTTPException(
            status_code=500,
            detail="The ML pipeline generated an invalid JSON result.",
        ) from exc

    except OSError as exc:
        logger.exception("Unable to read ML output")

        raise HTTPException(
            status_code=500,
            detail="Unable to read the analysis result.",
        ) from exc

    if not isinstance(result, dict):
        raise HTTPException(
            status_code=500,
            detail="The ML analysis result must be a JSON object.",
        )

    return result


async def save_upload_to_temp(
    resume: UploadFile,
    suffix: str,
) -> Path:
    """Save the uploaded file to a temporary path with a size limit."""

    temp_path = None
    total_size = 0

    try:
        with tempfile.NamedTemporaryFile(
            mode="wb",
            suffix=suffix,
            delete=False,
        ) as temp_file:

            temp_path = Path(temp_file.name)

            while True:
                chunk = await resume.read(1024 * 1024)

                if not chunk:
                    break

                total_size += len(chunk)

                if total_size > MAX_FILE_SIZE:
                    raise HTTPException(
                        status_code=413,
                        detail="Resume file must be smaller than 10 MB.",
                    )

                temp_file.write(chunk)

        if total_size == 0:
            raise HTTPException(
                status_code=400,
                detail="The uploaded resume is empty.",
            )

        return temp_path

    except Exception:
        if temp_path and temp_path.exists():
            temp_path.unlink(missing_ok=True)

        raise

    finally:
        await resume.close()


