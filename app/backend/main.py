@app.post("/analyze-resume")
async def analyze_resume(
    resume: UploadFile = File(...),
    target_role: str = Form(...),
):
    target_role = target_role.strip()

    if not target_role:
        raise HTTPException(
            status_code=400,
            detail="Please enter your target career role.",
        )

    if not resume.filename:
        raise HTTPException(
            status_code=400,
            detail="Please upload a resume.",
        )

    extension = Path(resume.filename).suffix.lower()

    if extension not in {".pdf", ".txt"}:
        await resume.close()

        raise HTTPException(
            status_code=400,
            detail="Only PDF and TXT resume files are supported.",
        )

    uploaded_path = None
    processed_path = None

    try:
        # ----------------------------------------------------
        # SAVE UPLOAD
        # ----------------------------------------------------

        uploaded_path = await save_upload_to_temp(
            resume,
            extension,
        )

        # ----------------------------------------------------
        # PREPARE RESUME FOR THE ML PIPELINE
        # ----------------------------------------------------

        if extension == ".pdf":
            extracted_text = extract_pdf_text(uploaded_path)

            with tempfile.NamedTemporaryFile(
                mode="w",
                suffix=".txt",
                delete=False,
                encoding="utf-8",
            ) as temp_file:

                processed_path = Path(temp_file.name)
                temp_file.write(extracted_text)

        else:
            processed_path = uploaded_path

        # ----------------------------------------------------
        # RUN ML PIPELINE
        # ----------------------------------------------------

        async with analysis_lock:

            logger.info(
                "Starting resume analysis for target role: %s",
                target_role,
            )

            # Import only after the project root has been configured.
            from ml.src.resume_analysis_pipeline import (
                run_complete_analysis,
            )

            # The pipeline is synchronous, so execute it in a
            # worker thread rather than blocking the event loop.
            await asyncio.to_thread(
                run_complete_analysis,
                str(processed_path),
                target_role,
            )

            # Read the result while holding the lock so another
            # request cannot overwrite the shared output first.
            analysis_result = read_analysis_json()

        logger.info("Resume analysis completed successfully")

        return {
            "status": "success",
            "message": "Resume analysis completed successfully.",
            "filename": Path(resume.filename).name,
            "target_role": target_role,
            "analysis": analysis_result,
        }

    except HTTPException:
        raise

    except Exception as exc:
        logger.exception("Resume analysis failed")

        raise HTTPException(
            status_code=500,
            detail=(
                "Resume analysis failed. Check the backend terminal "
                "for the detailed error."
            ),
        ) from exc

    finally:
        # Clean up temporary files.
        for temp_path in {uploaded_path, processed_path}:
            if temp_path and temp_path.exists():
                try:
                    temp_path.unlink(missing_ok=True)
                except OSError:
                    logger.warning(
                        "Could not remove temporary file: %s",
                        temp_path,
                    )


